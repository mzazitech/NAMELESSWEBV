const MODEL = 'gpt-5-mini';

async function chat(openai, system, prompt, max = 1024) {
    const res = await openai.chat.completions.create({
        model: MODEL,
        max_completion_tokens: max,
        messages: [
            ...(system ? [{ role: 'system', content: system }] : []),
            { role: 'user', content: prompt }
        ]
    });
    return res.choices?.[0]?.message?.content?.trim() || '(no response)';
}

const aiAlias = (names, system, opts = {}) => ({
    name: names[0],
    aliases: names.slice(1),
    category: 'ai',
    desc: opts.desc || `AI ${names[0]}`,
    run: async (ctx) => {
        const q = (ctx.text || '').trim();
        if (!q) return ctx.reply(`*Usage:* ${ctx.prefix}${ctx.command} <your prompt>\n\nExample: ${ctx.prefix}${ctx.command} ${opts.example || 'hello'}`);
        await ctx.m.react?.('⏳').catch(() => {});
        try {
            const reply = await chat(ctx.openai, system, q, opts.max || 1024);
            await ctx.reply(reply);
            await ctx.m.react?.('✅').catch(() => {});
        } catch (e) {
            await ctx.reply(`*AI error:* ${e?.message || e}`);
        }
    }
});

